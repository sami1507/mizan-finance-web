import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";

const baseURL = process.env.CAPTURE_URL || "http://localhost:3000";
await mkdir("docs/screenshots", { recursive: true });
await mkdir("public", { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto(baseURL, { waitUntil: "networkidle" });
await page.screenshot({ path: "docs/screenshots/landing-desktop.png", fullPage: true });
await page.goto(`${baseURL}/demo`);
await page.getByTestId("add-transaction").waitFor({ timeout: 90_000 });
await page.waitForLoadState("networkidle");
await page.screenshot({ path: "docs/screenshots/dashboard-desktop.png", fullPage: true });
await page.screenshot({ path: "public/dashboard-preview-ar.png" });
await page.getByTestId("language-toggle").click();
await page.screenshot({ path: "docs/screenshots/dashboard-english.png", fullPage: true });
await page.screenshot({ path: "public/dashboard-preview-en.png" });
await page.getByTestId("theme-toggle").click();
await page.screenshot({ path: "public/dashboard-preview-en-dark.png" });
await page.getByTestId("language-toggle").click();
await page.screenshot({ path: "docs/screenshots/dashboard-dark.png", fullPage: true });
await page.screenshot({ path: "public/dashboard-preview-ar-dark.png" });
await page.getByTestId("theme-toggle").click();
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: "docs/screenshots/dashboard-mobile.png", fullPage: true });
await page.screenshot({ path: "public/dashboard-preview-mobile-ar.png" });
await page.getByTestId("language-toggle").click();
await page.screenshot({ path: "public/dashboard-preview-mobile-en.png" });
await page.getByTestId("theme-toggle").click();
await page.screenshot({ path: "public/dashboard-preview-mobile-en-dark.png" });
await page.getByTestId("language-toggle").click();
await page.screenshot({ path: "public/dashboard-preview-mobile-ar-dark.png" });
await page.getByTestId("theme-toggle").click();
await page.goto(baseURL, { waitUntil: "networkidle" });
await page.screenshot({ path: "docs/screenshots/landing-mobile.png", fullPage: true });
await page.setViewportSize({ width: 1440, height: 1050 });
await page.reload({ waitUntil: "networkidle" });
await page.screenshot({ path: "docs/screenshots/landing-desktop.png", fullPage: true });
await page.screenshot({ path: "docs/screenshots/landing-viewport.png" });
await browser.close();
if (errors.length) throw new Error(errors.join("\n"));
console.log("Captured six demo-only screenshots; no browser page errors.");
